# Each pair is generated from an explicit bilingual sentence pattern and
# a hand-written Chinese/Thai vocabulary map; no corpus is downloaded.
buckets = defaultdict(list)
seen_zh = set()
for cat in data["categories"]:
    for row in cat["examples"]:
        seen_zh.add("".join(row["zh"].split()))

def add(topic, zh, th):
    zh, th = zh.strip(), th.strip()
    key = "".join(zh.split())
    if zh and th and key not in seen_zh:
        seen_zh.add(key)
        buckets[topic].append({"zh": zh, "th": th})

